def apply_faq(page):
    """Append this page's questions to its own FAQ block, on the page dict
    itself, before rendering - so the FAQPage schema, which is built from the
    same blocks, carries them too. Adds only."""
    spec = FAQ_ENTRIES.get(page["path"])
    if not spec:
        return page
    faq = next((b for b in page["blocks"] if b.get("type") == "faq"), None)
    if faq is None:
        raise SystemExit("gsc_phrases: %s has no FAQ block to extend"
                         % page["path"])
    have = {it.get("q", "").strip() for it in faq["items"]}
    for q, a in spec:
        if q in have:
            continue
        faq["items"].append({"q": q, "a": "<p>%s</p>" % a})
        CHANGES.append({"path": page["path"], "where": "faq", "heading": q})
    return page


def _find_faq(blocks):
    for i, b in enumerate(blocks):
        if b.get("type") == "faq":
            return i
    return None


def _last_content(blocks):
    for i in range(len(blocks) - 1, -1, -1):
        if blocks[i].get("type") in ("paragraph", "list", "table", "faq"):
            return i
    return len(blocks) - 1


def _section_end(blocks, prefix, path):
    """Index just past the section whose heading starts with `prefix`: the
    next heading at the same or a higher level, or the FAQ, or the end."""
    for i, b in enumerate(blocks):
        if b.get("type") == "heading" and (b.get("text") or "").strip().startswith(prefix):
            level = b.get("level", 2)
            for j in range(i + 1, len(blocks)):
                nb = blocks[j]
                if nb.get("type") == "faq":
                    return j
                if nb.get("type") == "heading" and nb.get("level", 2) <= level:
                    return j
            return len(blocks)
    # an anchor that stopped matching must not quietly fall back somewhere else
    raise SystemExit("gsc_phrases: no heading starting %r on %s" % (prefix, path))


def apply(body, path=""):
    """Insert this page's additions as an h3 and a paragraph - at the end of
    the section they belong to when an anchor is given, otherwise just above
    the FAQ. Adds only - nothing existing is moved or removed."""
    spec = ENTRIES.get(path)
    if not spec:
        return body

    for entry in spec:
        where = entry.get("at", "before_faq")
        if where.startswith("after:"):
            at = _section_end(body, where[len("after:"):], path)
        else:
            i = _find_faq(body)
            at = i if i is not None else _last_content(body) + 1
        at = max(0, min(at, len(body)))
        body = body[:at] + [
            {"type": "heading", "level": 3, "text": entry["h"], "html": entry["h"]},
            {"type": "paragraph", "html": entry["p"]},
        ] + body[at:]
        CHANGES.append({"path": path, "where": where, "heading": entry["h"]})
    return body
